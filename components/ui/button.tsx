/**
 * Always run through `cn`, because the class list CONTRADICTS ITSELF without
 * it: the base sets `border-transparent` and the outline variant sets
 * `border-border`, and only tailwind-merge collapses the pair. Left unmerged,
 * both survive and CSS source order picks the transparent one -- so every
 * outline button renders with an invisible border.
 *
 * <Button> already merged. The 39 places that pass buttonVariants(...) straight
 * into a className did not, which was every outline button on every page: the
 * dashboard's date presets, "Unduh CSV", the public booking page's "Lihat
 * jadwal". Found by looking at the public page on a phone and asking why the
 * primary call to action rendered as plain text.
 *
 * Merging HERE rather than at each call site is the fix that also covers the
 * fortieth one.
 */
function buttonVariants(
  props?: Parameters<typeof buttonVariantsBase>[0],
): string {
  return cn(buttonVariantsBase(props))
}

function Button({
  className,
  variant = "default",
  size = "default",
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariantsBase>) {
  return (
    <ButtonPrimitive
      data-slot="button"
      className={buttonVariants({ variant, size, className })}
      {...props}
    />
  )
}

export { Button, buttonVariants }
